"""
Feed the system beliefs so the network learns faster.

Two modes:

  backfill  Beliefs placed at random dates in the past (default 1-3 years
            back) and graded right away against what actually happened.
            Thousands of graded examples in an afternoon. Claude may know how
            those years played out, so backfilled rows are tagged
            source='seed_backfill', never expose Claude's score/rank to the
            network, and can be down-weighted or dropped later.

  live      Fresh beliefs submitted today as user 'seed'. Graded going
            forward like real users — clean data, no hindsight possible.
            Run daily from a cron job.

Beliefs come from seed_beliefs.txt plus (optionally) new ones generated by
Claude each run, so coverage keeps widening.

  auto      What the hourly cron runs. While the network is still warming up (fewer graded picks
            than MP_WARMUP_GRADED), it force-feeds a batch of past-dated beliefs every run, within a
            total budget (MP_WARMUP_BUDGET_USD). It also does the daily live batch once a day, then
            grades whatever is due and retrains. No one has to run anything by hand.

Examples:
  PYTHONPATH=./ python -m backend.v4.seeder auto
  PYTHONPATH=./ python -m backend.v4.seeder backfill --n 300 --max-usd 5
  PYTHONPATH=./ python -m backend.v4.seeder live --n 25 --generate 25
"""
from __future__ import annotations

import argparse
import json
import os
import random
import threading
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import date, timedelta
from typing import Optional

from . import db, engine, grader, interpreter, market

SEED_FILE = os.path.join(os.path.dirname(__file__), "seed_beliefs.txt")
SEED_MODEL = os.getenv("MP_SEED_MODEL", "claude-haiku-5-5")
RISKS = ("conservative", "moderate", "moderate", "aggressive")

GEN_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["beliefs"],
    "properties": {"beliefs": {"type": "array", "items": {"type": "string"}}},
}


def starter_beliefs() -> list[str]:
    with open(SEED_FILE, encoding="utf-8") as f:
        return [l.strip() for l in f if l.strip() and not l.startswith("#")]


def generate_beliefs(n: int, avoid: list[str], model: Optional[str] = None, client=None) -> list[str]:
    """Ask Claude for n new, varied beliefs in the voice of everyday users."""
    client = client or interpreter._client()
    sample = random.sample(avoid, min(40, len(avoid)))
    prompt = (
        f"Write {n} short beliefs that everyday people might type into an app that turns beliefs into trade ideas. "
        "Vary them widely: consumer habits, jobs, local observations, commodities, technology, health, travel, "
        "housing, energy, weather, culture, specific companies, macro. Mix bullish and bearish, short and long term, "
        "vague and specific. Write them casually, the way a person would, one belief per item. Avoid repeating these:\n- "
        + "\n- ".join(sample)
    )
    resp = client.messages.create(
        model=model or SEED_MODEL,
        max_tokens=4000,
        messages=[{"role": "user", "content": prompt}],
        extra_body={"output_config": {"effort": "low", "format": {"type": "json_schema", "schema": GEN_SCHEMA}}},
    )
    text = next((b.text for b in resp.content if getattr(b, "type", "") == "text"), "{}")
    beliefs = json.loads(text).get("beliefs", [])
    seen = {b.lower() for b in avoid}
    return [b.strip() for b in beliefs if b.strip() and b.strip().lower() not in seen][:n]


def _random_past_weekday(min_days_ago: int, max_days_ago: int) -> date:
    for _ in range(20):
        d = market.today() - timedelta(days=random.randint(min_days_ago, max_days_ago))
        if d.weekday() < 5:
            return d
    return d


def news_beliefs(limit: int) -> list[str]:
    """Today's real headlines as hunches (from the Moving now feed), each paired with its opposite so the
    network sees both sides of real news. Only ones not seeded before."""
    from . import movers
    try:
        items = movers.feed().get("items", [])
    except Exception as e:
        print(f"[seeder] news feed unavailable: {e}")
        return []
    used = {r["text"].lower() for r in db.query("SELECT DISTINCT text FROM beliefs WHERE source = 'seed_news'")}
    out = []
    for it in items:
        h = (it.get("hunch") or "").strip().rstrip(".")
        if not h or h == it.get("headline"):
            continue  # no AI rewrite: a raw headline isn't a belief
        for b in (h, f"I don't think {h[0].lower() + h[1:]}"):
            if b.lower() not in used and b not in out:
                out.append(b)
    return out[:limit]


def run(mode: str, n: int, generate: int = 0, years: float = 3.0, concurrency: int = 4,
        max_usd: float = 10.0, model: Optional[str] = None, claude_client=None,
        beliefs: Optional[list[str]] = None, source: Optional[str] = None) -> dict:
    model = model or SEED_MODEL
    if beliefs:
        generate = 0
    pool = list(beliefs) if beliefs else starter_beliefs()
    used = {r["text"].lower() for r in db.query("SELECT DISTINCT text FROM beliefs WHERE source LIKE 'seed%'")}
    if generate:
        try:
            pool += generate_beliefs(generate, pool + list(used), model=model, client=claude_client)
        except Exception as e:  # generation is optional; seeding continues with the starter list
            print(f"[seeder] belief generation failed: {e}")
    random.shuffle(pool)
    if mode == "live" and not beliefs:
        fresh = [b for b in pool if b.lower() not in used]
        pool = fresh or pool  # once everything was used, repeat (different day = different data)
    jobs = pool[:n] if beliefs else [pool[i % len(pool)] for i in range(n)]

    spent = 0.0
    lock = threading.Lock()
    results = {"ok": 0, "skipped": 0, "errors": 0, "cost_usd": 0.0}
    max_days = int(365 * years)

    def one(text: str) -> dict:
        as_of = _random_past_weekday(100, max_days) if mode == "backfill" else None
        return engine.process_belief(
            text, user_id="seed", risk_profile=random.choice(RISKS), as_of=as_of,
            source=source or ("seed_backfill" if mode == "backfill" else "seed_live"),
            model=model, claude_client=claude_client,
        )

    with ThreadPoolExecutor(max_workers=max(1, concurrency)) as ex:
        futures = []
        for text in jobs:
            with lock:
                if spent >= max_usd:
                    break
            futures.append(ex.submit(one, text))
        for f in as_completed(futures):
            try:
                r = f.result()
                with lock:
                    spent += float((r.get("usage") or {}).get("cost_usd", 0.0))
                    results["ok" if r.get("valid") else "skipped"] += 1
            except Exception as e:
                results["errors"] += 1
                print(f"[seeder] error: {e}")
            if spent >= max_usd:
                for other in futures:
                    other.cancel()
    results["cost_usd"] = round(spent, 4)
    if mode == "backfill":
        results["grading"] = grader.grade()
    return results


def _kv_get(k: str, default: str = "") -> str:
    row = db.query_one("SELECT v FROM kv_cache WHERE k = ?", (k,))
    return row["v"] if row else default


def _kv_set(k: str, v: str) -> None:
    from datetime import datetime, timezone
    db.execute("DELETE FROM kv_cache WHERE k = ?", (k,))
    db.execute("INSERT INTO kv_cache (k, v, created_at) VALUES (?,?,?)", (k, v, datetime.now(timezone.utc).isoformat()))


def auto(claude_client=None) -> dict:
    """Hourly: warm up with past-dated beliefs until there's enough graded history, seed live once a day,
    grade, retrain. Spending is capped in total (warm-up) and per day (live)."""
    from . import nn
    target = int(os.getenv("MP_WARMUP_GRADED", "4000"))
    budget = float(os.getenv("MP_WARMUP_BUDGET_USD", "8"))
    batch = int(os.getenv("MP_WARMUP_BATCH", "80"))
    out: dict = {}
    row = db.query_one("SELECT COUNT(DISTINCT pick_id) AS n FROM outcomes WHERE checkpoint_days = ?", (nn.LABEL_DAYS,))
    graded = int(row["n"] if row else 0)
    spent = float(_kv_get("warmup_spent_usd", "0") or 0)
    out["warmup"] = {"graded_at_label": graded, "target": target, "spent_usd": round(spent, 4), "budget_usd": budget}
    if graded < target and spent < budget:
        r = run("backfill", n=batch, generate=int(os.getenv("MP_WARMUP_GENERATE", "20")), years=3.0, concurrency=4,
                max_usd=min(1.0, budget - spent), claude_client=claude_client)
        _kv_set("warmup_spent_usd", str(spent + r["cost_usd"]))
        out["backfill"] = r
    today = market.today()
    if today.weekday() < 5 and _kv_get("live_seed_date") != today.isoformat():
        out["live"] = run("live", n=int(os.getenv("MP_SEED_N", "25")), generate=int(os.getenv("MP_SEED_GENERATE", "25")),
                          max_usd=float(os.getenv("MP_SEED_MAX_USD", "1")), claude_client=claude_client)
        _kv_set("live_seed_date", today.isoformat())
    # Real news, every hour: today's hunches and their opposites (graded at 1 week / 1 month / 3 months).
    news_n = int(os.getenv("MP_NEWS_SEED_N", "6"))
    day_key = f"news_seed_usd:{today.isoformat()}"
    news_spent = float(_kv_get(day_key, "0") or 0)
    news_cap = float(os.getenv("MP_NEWS_SEED_MAX_USD", "0.5"))
    if news_n > 0 and news_spent < news_cap:
        fresh = news_beliefs(news_n)
        if fresh:
            r = run("live", n=len(fresh), beliefs=fresh, source="seed_news", max_usd=news_cap - news_spent,
                    claude_client=claude_client)
            _kv_set(day_key, str(news_spent + r["cost_usd"]))
            out["news"] = dict(r, beliefs=fresh)
    g = grader.grade()
    out["grade"] = g
    if out.get("backfill") or g.get("graded"):
        res = nn.train()
        out["train"] = {k: res.get(k) for k in ("status", "reason", "n_train", "n_test", "spearman", "blend_weight")}
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description="Seed MarketPlayground with beliefs")
    ap.add_argument("mode", choices=["backfill", "live", "auto"])
    ap.add_argument("--n", type=int, default=int(os.getenv("MP_SEED_N", "25")), help="beliefs to process")
    ap.add_argument("--generate", type=int, default=int(os.getenv("MP_SEED_GENERATE", "0")),
                    help="also ask Claude for this many new beliefs")
    ap.add_argument("--years", type=float, default=3.0, help="backfill: how far back to place beliefs")
    ap.add_argument("--concurrency", type=int, default=4)
    ap.add_argument("--max-usd", type=float, default=float(os.getenv("MP_SEED_MAX_USD", "5")),
                    help="stop once Claude spend reaches this")
    ap.add_argument("--model", default=None, help=f"Claude model (default {SEED_MODEL})")
    args = ap.parse_args()
    if os.getenv("MP_SEED_ENABLED", "true").lower() not in ("1", "true", "yes"):
        print("seeding disabled (MP_SEED_ENABLED)")
        return
    if args.mode == "auto":
        print(json.dumps(auto(), indent=2, default=str))
        return
    print(json.dumps(run(args.mode, args.n, args.generate, args.years, args.concurrency, args.max_usd, args.model), indent=2))


if __name__ == "__main__":
    main()
